/* Devuelve el índice del glifo de un punto de código Unicode (107 = no lo tenemos). */
unsigned fuente_indice(u32 cp)
{
    static const u16 extra[][2] = {
        {0xE1,95},{0xE9,96},{0xED,97},{0xF3,98},{0xFA,99},{0xF1,100},{0xD1,101},
        {0xBF,102},{0xA1,103},{0xAB,104},{0xBB,105},{0xB0,106},
        {0xFC,108},{0xDC,109},{0xC1,110},{0xC9,111},{0xCD,112},{0xD3,113},{0xDA,114},
        {0x2190,115},{0x2192,116},{0x2191,117},{0x2193,118},{0x2713,119},{0x2022,120},{0xB7,121},{0x2026,122} };
    unsigned i;
    if (cp >= 32 && cp < 127) return cp - 32;
    for (i = 0; i < sizeof extra / sizeof extra[0]; i++) if (extra[i][0] == cp) return extra[i][1];
    return 107;
}
